"""The data a report produces, independent of how it is shown or exported."""

from dataclasses import dataclass
from datetime import date, datetime


def format_value(value):
    """Dates as DD-MM-YYYY (as in the Test Plan), None as an empty cell."""
    if value is None:
        return ""
    if isinstance(value, datetime):
        return value.strftime("%d-%m-%Y %H:%M:%S")
    if isinstance(value, date):
        return value.strftime("%d-%m-%Y")
    return str(value)


@dataclass(frozen=True)
class ReportResult:
    title: str
    columns: tuple[str, ...]
    rows: tuple[tuple, ...]
    start: date
    end: date
    generated_by: str
    generated_at: datetime

    @property
    def provenance(self):
        """The REQ-43 header: report name, date range, user and timestamp."""
        return (
            ("Report", self.title),
            ("Date range", f"{format_value(self.start)} to {format_value(self.end)}"),
            ("Generated by", self.generated_by),
            ("Generated at", format_value(self.generated_at)),
        )
