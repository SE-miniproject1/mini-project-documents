import csv
import io
from datetime import date, datetime

from django.test import SimpleTestCase

from reports.services.export import to_csv
from reports.services.result import ReportResult


def sample_result(rows=(("O-", "PRBC", 8), ("A+", "PRBC", 12))):
    return ReportResult(
        title="Inventory Status Report",
        columns=("Blood Group", "Component Type", "Available Count"),
        rows=rows,
        start=date(2026, 9, 1),
        end=date(2026, 9, 30),
        generated_by="staff01",
        generated_at=datetime(2026, 10, 31, 18, 30, 5),
    )


def parse(data):
    return list(csv.reader(io.StringIO(data.decode("utf-8"), newline="")))


class CsvExportTests(SimpleTestCase):
    """UT-45 (CSV): provenance header and RFC 4180 conformance."""

    def test_header_carries_name_range_user_and_timestamp(self):
        rows = parse(to_csv(sample_result()))
        self.assertEqual(rows[0][:2], ["Report", "Inventory Status Report"])
        self.assertEqual(rows[1][:2], ["Date range", "01-09-2026 to 30-09-2026"])
        self.assertEqual(rows[2][:2], ["Generated by", "staff01"])
        self.assertEqual(rows[3][:2], ["Generated at", "31-10-2026 18:30:05"])

    def test_columns_and_data_follow_the_header(self):
        rows = parse(to_csv(sample_result()))
        self.assertEqual(rows[5], ["Blood Group", "Component Type", "Available Count"])
        self.assertEqual(rows[6], ["O-", "PRBC", "8"])
        self.assertEqual(rows[7], ["A+", "PRBC", "12"])

    def test_every_record_has_the_same_number_of_fields(self):
        rows = parse(to_csv(sample_result()))
        self.assertEqual({len(row) for row in rows}, {3})

    def test_lines_end_with_crlf(self):
        data = to_csv(sample_result())
        self.assertEqual(data.count(b"\n"), data.count(b"\r\n"))

    def test_commas_and_quotes_survive_a_round_trip(self):
        rows = parse(to_csv(sample_result(rows=(("A, B", 'say "hi"', 1),))))
        self.assertEqual(rows[6], ["A, B", 'say "hi"', "1"])

    def test_formula_text_is_neutralised_but_numbers_are_not(self):
        rows = parse(to_csv(sample_result(rows=(("=1+1", "O-", -5),))))
        self.assertEqual(rows[6], ["'=1+1", "O-", "-5"])
